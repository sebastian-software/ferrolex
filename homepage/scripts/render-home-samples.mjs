/* eslint-disable security/detect-non-literal-fs-filename -- Only fixed, repository-owned paths are read or written. */
/**
 * Writes app/data/home-samples.json, the real output the homepage shows: the
 * explanations, checks, suggestions and budgets printed by homepage/samples, a
 * small program that depends on the released ferrolex crates at the Git tag
 * pinned in homepage/samples/Cargo.toml (Ferrolex is not on crates.io yet).
 *
 * The program installs the reviewed LibreOffice en_US and de_DE dictionaries
 * through the release's own digest-checked installer into
 * target/homepage-samples/dictionaries, outside the repository's tracked files.
 * No dictionary content is committed.
 *
 * - `pnpm sample:write` renders and writes the file.
 * - `pnpm sample:check` renders again and fails when the file no longer matches.
 * - `pnpm sample:pins` (part of `pnpm verify`, so CI) checks without rendering:
 *   ferrolex never downloads a dictionary in CI, so CI only proves that the
 *   committed file names the pinned release and commit and is well formed.
 *
 * Nobody edits the file by hand.
 */
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "oxfmt";

const root = fileURLToPath(new URL("../../", import.meta.url));
const mode = process.argv.includes("--pins")
  ? "pins"
  : process.argv.includes("--check")
    ? "check"
    : "write";
const destination = new URL("../app/data/home-samples.json", import.meta.url);
const repository = (path) => new URL(`../../${path}`, import.meta.url);
/** Git on Windows may check text out with CRLF; compare content, not line endings. */
const lf = (text) => text.replaceAll("\r\n", "\n");
const locales = (list) => list.map((entry) => entry.locale);

// The pin: every ferrolex crate at one release tag, and the commit Cargo locked.
const manifest = await readFile(new URL("../samples/Cargo.toml", import.meta.url), "utf8");
const tags = [...manifest.matchAll(/^ferrolex-[a-z]+ = \{ git = "[^"]+", tag = "([^"]+)" \}$/gm)];
assert.equal(tags.length, 4, "homepage/samples/Cargo.toml must pin four ferrolex crates.");
const tag = tags[0][1];
assert(
  tags.every(([, entry]) => entry === tag),
  "Pin every ferrolex crate to the same release tag.",
);
const pinned = /^ferrolex-v(\d+\.\d+\.\d+)$/.exec(tag)?.[1];
assert(pinned, `${tag} is not a ferrolex release tag.`);
const lock = await readFile(new URL("../samples/Cargo.lock", import.meta.url), "utf8");
const locked = lock.split("\n").find((line) => line.includes(`?tag=${tag}#`)) ?? "";
const commit = /#([0-9a-f]{40})"$/.exec(locked)?.[1];
assert(commit, `homepage/samples/Cargo.lock does not lock ${tag} to a commit.`);
const releases = JSON.parse(await readFile(repository(".release-please-manifest.json"), "utf8"));
const release = releases["."];
if (pinned !== release) {
  const message = `Rendering with ferrolex ${pinned}; the current release is ${release}. Move the tags in homepage/samples/Cargo.toml to ferrolex-v${release}.`;
  if (mode === "write") console.warn(message);
  else assert.fail(message);
}
const renderedWith = { ferrolex: pinned, tag, commit };

if (mode === "pins") {
  const samples = JSON.parse(lf(await readFile(destination, "utf8")));
  assert.deepEqual(
    samples.renderedWith,
    renderedWith,
    "The homepage samples were rendered with another release. Run pnpm sample:write.",
  );
  verify(samples);
  console.log(`The homepage samples name ferrolex ${pinned} (${commit.slice(0, 7)}).`);
} else {
  const specimens = JSON.parse(
    execFileSync(
      "cargo",
      [
        "run",
        "--locked",
        "--release",
        "--quiet",
        "--manifest-path",
        "homepage/samples/Cargo.toml",
        "--target-dir",
        "target/homepage-samples",
        "--",
        "target/homepage-samples/dictionaries",
      ],
      { cwd: root, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
    ),
  );
  const samples = {
    note: "Generated by homepage/scripts/render-home-samples.mjs. Do not edit.",
    renderedWith,
    ...specimens,
  };
  verify(samples);
  const formatted = await format("home-samples.json", JSON.stringify(samples));
  assert.equal(formatted.errors.length, 0);
  if (mode === "check") {
    assert.equal(
      lf(await readFile(destination, "utf8")),
      formatted.code,
      "The homepage samples changed. Run pnpm sample:write and commit the result.",
    );
    console.log(`The homepage samples match ferrolex ${pinned}.`);
  } else {
    await mkdir(new URL(".", destination), { recursive: true });
    await writeFile(destination, formatted.code);
    console.log(`Wrote app/data/home-samples.json with ferrolex ${pinned}.`);
  }
}

/** What the page's text relies on; a new release that changes it needs new words. */
function verify(samples) {
  assert.deepEqual(locales(samples.dictionaries), ["en_US", "de_DE"]);
  assert.deepEqual(locales(samples.explain), ["en_US", "de_DE"]);
  assert.deepEqual(locales(samples.check), ["en_US", "de_DE"]);
  const explained = Object.fromEntries(
    samples.explain.flatMap((entry) => entry.words.map((word) => [word.word, word])),
  );
  assert.equal(explained.WALKED?.casing?.path, "fallback", "WALKED should need the case fallback.");
  assert.equal(explained.paris?.accepted, false, "A lowercase paris should be rejected.");
  assert.equal(explained.Wörterbuch?.accepted, false, "The page says Wörterbuch is not accepted.");
  const runs = samples.budget.runs.map((run) => [run.id, run.completeness]);
  assert.deepEqual(
    runs,
    [
      ["small", "candidate-limit"],
      ["default", "edit-budget"],
      ["large", "complete"],
    ],
    "The budget section describes these three outcomes.",
  );
  const [, standard, large] = samples.budget.runs;
  assert.deepEqual(standard.suggestions, large.suggestions, "The larger budget should agree.");
}
